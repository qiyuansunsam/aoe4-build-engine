w("## Current patch effective rates, res/min per villager (model), d = typical one-way distance\n")
w("| res | d | none | Wheelbarrow | +tier1 tech | +tier2 | all eco techs | all techs, d+3 tiles |\n|---|---|---|---|---|---|---|---|")
for res, techs in ALL.items():
    d = TYP[res]
    def rate(t, dd=d):
        if res == "sheep": return 60 * sheep_group_rate(8, t, d=dd) / 8
        return 60 * r_eff(res, dd, t)
    vals = [rate(()), rate(WB), rate(techs[:2]), rate(techs[:3]), rate(techs), rate(techs, d + 3)]
    w(f"| {res} | {d} | " + " | ".join(f"{v:.1f}" for v in vals) + " |")
